// lineCount is what one unit changed, from git diff --numstat over its commits
// (RFC-0005 3.3).
type lineCount struct {
	code, docs int64    // added plus deleted, counted
	added      int64    // counted added lines, for the pure-deletion rule
	excluded   []string // binary, lockfile and linguist-generated paths, sorted
	tier       comb.RiskTier
}

// numstat reads the changes commit c brought to its first parent (or to the
// empty tree for a root commit): added, deleted and path, with renames off. A
// binary file has "-" counts.
func (g repo) numstat(ctx context.Context, c *commit) ([]numRow, error) {
	args := []string{"diff-tree", "-r", "-z", "--no-renames", "--numstat", "--no-commit-id"}
	if len(c.parents) == 0 {
		args = append(args, "--root", c.oid)
	} else {
		args = append(args, c.parents[0], c.oid)
	}
	out, err := g.run(ctx, nil, args...)
	if err != nil {
		return nil, err
	}
	var rows []numRow
	for _, rec := range strings.Split(strings.TrimSuffix(string(out), "\x00"), "\x00") {
		if rec == "" {
			continue
		}
		f := strings.SplitN(rec, "\t", 3)
		if len(f) != 3 {
			return nil, fmt.Errorf("nectar: unexpected numstat record")
		}
		r := numRow{path: f[2], binary: f[0] == "-"}
		if !r.binary {
			a, err1 := strconv.ParseInt(f[0], 10, 64)
			d, err2 := strconv.ParseInt(f[1], 10, 64)
			if err1 != nil || err2 != nil {
				return nil, fmt.Errorf("nectar: unexpected numstat counts")
			}
			r.added, r.deleted = a, d
		}
		rows = append(rows, r)
	}
	return rows, nil
}

type numRow struct {
	path           string
	added, deleted int64
	binary         bool
}

// countLines adds the rows of commit c into lc. policy gives each path's tier.
func (r *rules) countLines(ctx context.Context, g repo, c *commit, policy comb.TierPolicy, lc *lineCount) error {
	rows, err := g.numstat(ctx, c)
	if err != nil {
		return err
	}
	gen, err := g.generated(ctx, c.oid, rows, r.generatedAttr)
	if err != nil {
		return err
	}
	for _, row := range rows {
		lc.tier = max(lc.tier, policy.RequiredMinTier(row.path))
		switch {
		case row.binary || r.isLockfile(row.path) || gen[row.path]:
			lc.excluded = append(lc.excluded, row.path)
		case r.isDocs(row.path):
			lc.docs += row.added + row.deleted
			lc.added += row.added
		default:
			lc.code += row.added + row.deleted
			lc.added += row.added
		}
	}
	return nil
}

// tierPolicyAt reads gate.protected_paths from the config at commit oid. A
// missing, oversized or unparsable file at an old base means no extra paths, as
// an absent file does for the gate.
func (g repo) tierPolicyAt(ctx context.Context, oid string) (comb.TierPolicy, error) {
	cfg, err := g.configAt(ctx, oid)
	if err != nil || cfg == nil {
		return comb.TierPolicy{}, nil
	}
	return comb.TierPolicy{ExtraTier3: cfg.Gate.ProtectedPaths}, nil
}

// configAt parses the hive config as committed at oid; nil means no file.
func (g repo) configAt(ctx context.Context, oid string) (*config.Config, error) {
	blobs, err := g.batch(ctx, []string{oid + ":.waggle/control/config.yaml"})
	if err != nil || blobs[0] == nil {
		return nil, err
	}
	if len(blobs[0]) > config.MaxFileSize {
		return nil, fmt.Errorf("nectar: config at %s is over %d bytes", oid, config.MaxFileSize)
	}
	return config.Parse(blobs[0])
}

// generated returns the paths marked linguist-generated by the .gitattributes
// files committed at oid, never the worktree's. Only the directories of the
// changed paths are read.
func (g repo) generated(ctx context.Context, oid string, rows []numRow, attr string) (map[string]bool, error) {
	dirSet := map[string]bool{"": true}
	for _, r := range rows {
		for d := path.Dir(r.path); d != "."; d = path.Dir(d) {
			dirSet[d] = true
		}
	}
	dirs := make([]string, 0, len(dirSet))
	for d := range dirSet {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	specs := make([]string, len(dirs))
	for i, d := range dirs {
		specs[i] = oid + ":" + path.Join(d, ".gitattributes")
	}
	blobs, err := g.batch(ctx, specs)
	if err != nil {
		return nil, err
	}
	rulesByDir := map[string][]attrRule{}
	any := false
	for i, b := range blobs {
		if b != nil {
			rulesByDir[dirs[i]] = parseAttrs(string(b), attr)
			any = true
		}
	}
	res := map[string]bool{}
	if !any {
		return res, nil
	}
	for _, r := range rows {
		// Parent directories first, so a deeper file overrides a shallower one.
		state := false
		for _, d := range dirs {
			if d != "" && !strings.HasPrefix(r.path, d+"/") {
				continue
			}
			rel := strings.TrimPrefix(strings.TrimPrefix(r.path, d), "/")
			for _, ar := range rulesByDir[d] {
				if ar.re.MatchString(rel) {
					state = ar.set
				}
			}
		}
		if state {
			res[r.path] = true
		}
	}
	return res, nil
}

type attrRule struct {
	re  *regexp.Regexp
	set bool
}

// parseAttrs reads the lines of one .gitattributes that set or unset attr. A
// pattern without a slash matches the base name at any depth below the file.
func parseAttrs(text, attr string) []attrRule {
	var out []attrRule
	for _, line := range strings.Split(text, "\n") {
		f := strings.Fields(line)
		if len(f) < 2 || strings.HasPrefix(f[0], "#") {
			continue
		}
		var set, seen bool
		for _, a := range f[1:] {
			switch a {
			case attr, attr + "=true":
				set, seen = true, true
			case "-" + attr, "!" + attr, attr + "=false":
				set, seen = false, true
			}
		}
		if !seen {
			continue
		}
		if re := globRegexp(f[0]); re != nil {
			out = append(out, attrRule{re, set})
		}
	}
	return out
}

func globRegexp(p string) *regexp.Regexp {
	anchored := strings.Contains(strings.TrimSuffix(p, "/"), "/")
	p = strings.TrimPrefix(strings.TrimSuffix(p, "/"), "/")
	var b strings.Builder
	b.WriteString("^")
	if !anchored {
		b.WriteString("(?:.*/)?")
	}
	for i := 0; i < len(p); i++ {
		switch {
		case strings.HasPrefix(p[i:], "**/"):
			b.WriteString("(?:.*/)?")
			i += 2
		case strings.HasPrefix(p[i:], "**"):
			b.WriteString(".*")
			i++
		case p[i] == '*':
			b.WriteString("[^/]*")
		case p[i] == '?':
			b.WriteString("[^/]")
		default:
			b.WriteString(regexp.QuoteMeta(string(p[i])))
		}
	}
	b.WriteString("$")
	re, err := regexp.Compile(b.String())
	if err != nil {
		return nil
	}
	return re
}
