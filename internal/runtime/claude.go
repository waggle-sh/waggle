package runtime

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/waggle-sh/waggle/internal/layout"
)

// GeneratedMarker is the first frontmatter line of every generated shim. Waggle
// only overwrites or removes files in .claude/agents/ that carry it.
const GeneratedMarker = "# waggle:generated"

// ClaudeAdapter implements AgentRuntime for the `claude` CLI (Claude Code).
type ClaudeAdapter struct {
	cfg AdapterConfig
}

// NewClaudeAdapter returns a configured Claude Code runtime adapter.
func NewClaudeAdapter(cfg AdapterConfig) *ClaudeAdapter {
	if cfg.Binary == "" {
		cfg.Binary = "claude"
	}
	return &ClaudeAdapter{cfg: cfg}
}

func (c *ClaudeAdapter) Name() string {
	return "claude-code"
}

func (c *ClaudeAdapter) Config() AdapterConfig {
	return c.cfg
}

// IsGeneratedShim reports whether content carries GeneratedMarker on a line of its own.
func IsGeneratedShim(content []byte) bool {
	return bytes.Contains(content, []byte("\n"+GeneratedMarker+"\n"))
}

// Materialize reads the role prompts in .waggle/control/roles/*.md and writes
// Claude Code agent shims to .claude/agents/waggle-<role>.md. Frontmatter keeps
// name: <role>, so `claude --agent <role>` works. Shims are gitignored runtime
// state. A file at a shim path without GeneratedMarker is left untouched, and
// Materialize never writes CLAUDE.md.
func (c *ClaudeAdapter) Materialize(repoDir string) error {
	rolesDir := filepath.Join(repoDir, filepath.FromSlash(layout.RolesDir))
	shimPrefix := filepath.Join(repoDir, filepath.FromSlash(layout.ShimPrefix))

	entries, err := os.ReadDir(rolesDir)
	if err != nil {
		return fmt.Errorf("reading %s: %w", layout.RolesDir, err)
	}
	if err := os.MkdirAll(filepath.Dir(shimPrefix), 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Dir(layout.ShimPrefix), err)
	}

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		role := strings.TrimSuffix(entry.Name(), ".md")
		rel := layout.ShimPrefix + entry.Name()
		dstPath := shimPrefix + entry.Name()

		body, err := os.ReadFile(filepath.Join(rolesDir, entry.Name()))
		if err != nil {
			return fmt.Errorf("reading role %s: %w", role, err)
		}

		existing, err := os.ReadFile(dstPath)
		if err == nil && !IsGeneratedShim(existing) {
			fmt.Printf("  [skip]   %s (not generated by waggle)\n", rel)
			continue
		} else if err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("reading %s: %w", rel, err)
		}

		shim := fmt.Sprintf("---\n%s\nname: %s\ndescription: Waggle %s role, generated from %s/%s.md; edit the source, not this file\n---\n\n%s",
			GeneratedMarker, role, role, layout.RolesDir, role, body)
		if err := os.WriteFile(dstPath, []byte(shim), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", rel, err)
		}
		fmt.Printf("  [shim]   %s\n", rel)
	}
	return nil
}

// Run executes a single turn/session of Claude Code (implemented in Commit #2 with waggled).
// It refuses any Invocation whose Selection was not produced by Policy.Resolve
// for the same role, so a launch can never fall back to the session model.
func (c *ClaudeAdapter) Run(ctx context.Context, inv Invocation) (UsageStats, error) {
	if !inv.Selection.resolved || inv.Selection.Role != inv.Role {
		return UsageStats{}, fmt.Errorf("%w: role %s task %s", ErrUnresolved, inv.Role, inv.TaskID)
	}
	return UsageStats{}, fmt.Errorf("runtime execution requires waggled (Commit #2)")
}

// claudeArgs assembles the launch argv: the resolved model, then DefaultArgs.
// The waggled launch path uses it so the model always comes from a Selection.
func (c *ClaudeAdapter) claudeArgs(inv Invocation) []string {
	args := []string{"--model", inv.Selection.Model}
	return append(args, c.cfg.DefaultArgs...)
}
