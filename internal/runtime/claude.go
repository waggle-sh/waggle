package runtime

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ClaudeAdapter implements AgentRuntime for the `claude` CLI (Claude Code).
type ClaudeAdapter struct {
	cfg AdapterConfig
}

// NewClaudeAdapter returns a configured Claude Code runtime adapter.
func NewClaudeAdapter(cfg AdapterConfig) *ClaudeAdapter {
	if cfg.Binary == "" {
		cfg.Binary = "claude"
	}
	return &ClaudeAdapter{cfg: cfg}
}

func (c *ClaudeAdapter) Name() string {
	return "claude-code"
}

func (c *ClaudeAdapter) Config() AdapterConfig {
	return c.cfg
}

// Materialize reads the portable role definitions in .waggle/roles/*.md and generates
// Claude-specific agent files in .claude/agents/*.md with proper YAML frontmatter,
// plus a root CLAUDE.md pointer to WAGGLE.md. All generated files are gitignored.
func (c *ClaudeAdapter) Materialize(repoDir string) error {
	rolesDir := filepath.Join(repoDir, ".waggle", "roles")
	claudeAgentsDir := filepath.Join(repoDir, ".claude", "agents")

	// Ensure .claude/agents directory exists locally.
	if err := os.MkdirAll(claudeAgentsDir, 0o755); err != nil {
		return fmt.Errorf("creating .claude/agents directory: %w", err)
	}

	entries, err := os.ReadDir(rolesDir)
	if err != nil {
		return fmt.Errorf("reading .waggle/roles directory: %w", err)
	}

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}

		roleName := strings.TrimSuffix(entry.Name(), ".md")
		srcPath := filepath.Join(rolesDir, entry.Name())
		dstPath := filepath.Join(claudeAgentsDir, entry.Name())

		body, err := os.ReadFile(srcPath)
		if err != nil {
			return fmt.Errorf("reading role %s: %w", srcPath, err)
		}

		// Wrap the portable markdown role in Claude Code's expected YAML frontmatter
		// so `claude --agent <role>` works natively out of the box.
		withFrontmatter := fmt.Sprintf(`---
name: %s
description: Waggle %s role (generated from .waggle/roles/%s.md — edit source in .waggle/roles/)
---

%s`, roleName, roleName, roleName, string(body))

		if err := os.WriteFile(dstPath, []byte(withFrontmatter), 0o644); err != nil {
			return fmt.Errorf("writing materialized agent %s: %w", dstPath, err)
		}
		fmt.Printf("  [shim]   .claude/agents/%s\n", entry.Name())
	}

	// Write a lightweight CLAUDE.md that imports WAGGLE.md so Claude Code loads
	// the Hive architecture map automatically while keeping WAGGLE.md as the single source of truth.
	claudeMDPath := filepath.Join(repoDir, "CLAUDE.md")
	claudeMDContent := `<!-- Generated by waggle. Do not commit; edit WAGGLE.md instead. -->
@WAGGLE.md
`
	if err := os.WriteFile(claudeMDPath, []byte(claudeMDContent), 0o644); err != nil {
		return fmt.Errorf("writing CLAUDE.md shim: %w", err)
	}
	fmt.Println("  [shim]   CLAUDE.md -> @WAGGLE.md")

	return nil
}

// Run executes a single turn/session of Claude Code (implemented in Commit #2 with waggled).
func (c *ClaudeAdapter) Run(ctx context.Context, inv Invocation) (UsageStats, error) {
	return UsageStats{}, fmt.Errorf("runtime execution requires waggled (Commit #2)")
}
