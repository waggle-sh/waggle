package main

import "strings"

// collisionKey is the head tree collision check's comparison key (T-074):
// canonical decomposition, lower casing, then decomposition again for the
// single rune forms that lower case into a composed letter (U+212B to a
// precomposed a with ring). Two paths with one key are one name on a checkout
// that ignores case and normalization, such as APFS. Only decomposeTable and
// Hangul are decomposed, and marks on one base are not reordered (docs/gate.md
// section 4). An invalid UTF-8 byte becomes U+FFFD, as strings.ToLower does.
func collisionKey(p string) string {
	ascii := true
	for i := 0; i < len(p); i++ {
		if p[i] >= 0x80 {
			ascii = false
			break
		}
	}
	if ascii {
		return strings.ToLower(p)
	}
	return decomposeRunes(strings.ToLower(decomposeRunes(p)))
}

// decomposeRunes returns s with every rune that has an entry in decomposeTable,
// and every precomposed Hangul syllable, replaced by its canonical parts.
func decomposeRunes(s string) string {
	var b strings.Builder
	b.Grow(len(s) + len(s)/2)
	for _, r := range s {
		appendDecomposed(&b, r)
	}
	return b.String()
}

// appendDecomposed writes r, decomposed recursively.
func appendDecomposed(b *strings.Builder, r rune) {
	const (
		sBase, lBase, vBase, tBase = 0xAC00, 0x1100, 0x1161, 0x11A7
		tCount, nCount, sCount     = 28, 21 * 28, 19 * 21 * 28
	)
	if i := r - sBase; i >= 0 && i < sCount {
		b.WriteRune(lBase + i/nCount)
		b.WriteRune(vBase + i%nCount/tCount)
		if t := i % tCount; t != 0 {
			b.WriteRune(tBase + t)
		}
		return
	}
	if d, ok := decomposeTable[r]; ok {
		appendDecomposed(b, d[0])
		appendDecomposed(b, d[1])
		return
	}
	b.WriteRune(r)
}

// collisionText is the finding text for a pair with one key. A pair that
// differs in case alone keeps the text the check had before T-074.
func collisionText(prev, p string) string {
	if strings.ToLower(prev) == strings.ToLower(p) {
		return "path collides with " + prev + " on case-insensitive checkouts"
	}
	return "path collides with " + prev + " on checkouts that treat Unicode normalization forms as one name"
}

